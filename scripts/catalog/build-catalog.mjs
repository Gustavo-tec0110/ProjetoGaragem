/* global console, process */
// Generates LOCAL files only. Applying SQL or publishing assets is a separate release.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import sharp from 'sharp';
const root=process.cwd();
const read=async p=>JSON.parse(await readFile(p,'utf8'));
const definitions=await read('src/lib/modifications/catalog-definitions.json');
const baseline=await read('docs/catalogo-2026-10-27/baseline.json');
const reviews=await read('docs/catalogo-2026-10-27/photo-review.json');
const licenseEvidence=await read('docs/catalogo-2026-10-27/license-evidence.json');
const oldItems=new Map(baseline.tables.modification_catalog.map(x=>[x.slug,x]));
const categories=baseline.tables.modification_categories;
const folders={'motor-performance':'engine',suspensao:'suspension',freios:'brakes','rodas-pneus':'wheels',transmissao:'transmission',interior:'interior',exterior:'exterior',iluminacao:'lighting','eletrica-eletronica':'electrical',som:'audio'};
const assets={};const audit=[];
for(const item of definitions){
 const old=oldItems.get(item.slug);const review=reviews[item.slug];
 if(!review)throw new Error(`Missing review ${item.slug}`);
 let image=null;
 let sourceBytes=null;
 if(review.status==='approved'){
  try{sourceBytes=await readFile(review.file);}catch(error){if(error.code!=='ENOENT')throw error;}
  const evidence=licenseEvidence[review.source.title];
  if(!evidence || evidence.LicenseShortName?.value!==review.source.license || evidence.Restrictions?.value)throw new Error(`Unverified photo license: ${item.slug}`);
 }
 if(review.status==='approved' && review.output?.pipeline==='square-v2' && review.output.sourceTitle===review.source.title && (!sourceBytes || review.output.inputSha256===createHash('sha256').update(sourceBytes).digest('hex'))){
  const bytes=await readFile(path.join(root,'public',review.output.path));
  const metadata=await sharp(bytes).metadata();
  if(createHash('sha256').update(bytes).digest('hex')!==review.output.sha256 || metadata.width!==512 || metadata.height!==512 || metadata.format!=='webp') throw new Error(`Invalid reviewed output: ${item.slug}`);
  image=review.output.path;
 } else if(review.status==='approved'){
  if(!sourceBytes)throw new Error(`Missing reviewed input: ${item.slug}`);
  const input=sourceBytes;
  // Never crop or stretch. EXIF orientation first; center the complete source.
  const {data,info}=await sharp(input).rotate().resize({width:480,height:480,fit:'inside',withoutEnlargement:true}).flatten({background:'#f5f5f5'}).toBuffer({resolveWithObject:true});
  const left=Math.floor((512-info.width)/2), top=Math.floor((512-info.height)/2);
  const output=await sharp(data).extend({top,bottom:512-info.height-top,left,right:512-info.width-left,background:'#f5f5f5'}).webp({quality:84,effort:6}).toBuffer();
  const hash=createHash('sha256').update(output).digest('hex');
  const dest=`/modifications/${folders[item.category]}/${hash}.webp`;
  await writeFile(path.join(root,'public',dest),output);image=dest;
  review.output={pipeline:'square-v2',sourceTitle:review.source.title,inputSha256:createHash('sha256').update(input).digest('hex'),path:dest,sha256:hash,bytes:output.length};
 }
 assets[item.slug]={category:item.category,image,previousPaths:[...new Set([old?.default_image_path,old?`/modifications/${folders[item.category]}/${item.slug}.webp`:null].filter(Boolean))]};
 audit.push({...item,originalId:old?.id??null,previousImage:old?.default_image_path??null,image,review});
}
await writeFile('docs/catalogo-2026-10-27/photo-review.json',JSON.stringify(reviews,null,2)+'\n');
await writeFile('src/lib/modifications/catalog-assets.json',JSON.stringify(assets,null,2)+'\n');
await writeFile('docs/catalogo-2026-10-27/audit.json',JSON.stringify(audit,null,2)+'\n');
const quote=v=>v===null||v===undefined?'null':`'${String(v).replaceAll("'","''")}'`;
const values=definitions.map(x=>`  (${[x.slug,x.category,x.name,x.description,assets[x.slug].image,oldItems.get(x.slug)?.name??null,oldItems.get(x.slug)?.default_image_path??null,oldItems.has(x.slug)].map(v=>typeof v==='boolean'?String(v):quote(v)).join(', ')})`).join(',\n');
const sql=`-- Generated by scripts/catalog/build-catalog.mjs. Reviewed inventory: docs/catalogo-2026-10-27/audit.json.
-- LOCAL preparation only. Do not apply to production without release authorization.
-- IDs, slugs, references, category identities, RLS, grants, costs and compatibility of existing rows are preserved.
begin;
create temporary table catalog_expansion_20261027 (
  slug text primary key, category_slug text not null, name text not null,
  description text not null, image text, previous_name text, previous_image text, legacy boolean not null
) on commit drop;
insert into catalog_expansion_20261027 values
${values};

do $$ begin
  if exists (select 1 from catalog_expansion_20261027 s left join public.modification_categories c
    on c.slug=s.category_slug where c.id is null or not c.is_active) then
    raise exception 'Catalog expansion requires the ten existing active categories';
  end if;
end $$;

-- Never overwrite a preexisting slug or reactivate a deliberately disabled row.
insert into public.modification_catalog (category_id,slug,name,short_description,default_image_path,compatibility_type,compatibility_notes)
select c.id,s.slug,s.name,s.description,s.image,'adaptable',
  'Tipo de componente. A aplicação depende do veículo, das medidas e do projeto; a foto não comprova compatibilidade.'
from catalog_expansion_20261027 s join public.modification_categories c on c.slug=s.category_slug
where not s.legacy
on conflict (slug) do nothing;

-- Editorial corrections only while the original name/description has not been curated independently.
update public.modification_catalog m set name=s.name
from catalog_expansion_20261027 s join public.modification_categories c on c.slug=s.category_slug
where s.legacy and m.slug=s.slug and m.category_id=c.id and m.name=s.previous_name and m.name is distinct from s.name;
update public.modification_catalog m set short_description=s.description
from catalog_expansion_20261027 s join public.modification_categories c on c.slug=s.category_slug
where s.legacy and m.slug=s.slug and m.category_id=c.id and m.short_description is null;

-- Replace only known defaults. Unknown/manual image choices and inactive status are retained.
update public.modification_catalog m set default_image_path=s.image
from catalog_expansion_20261027 s join public.modification_categories c on c.slug=s.category_slug
where s.legacy and m.slug=s.slug and m.category_id=c.id
  and (m.default_image_path is null or m.default_image_path is not distinct from s.previous_image
    or m.default_image_path=('/modifications/' || case s.category_slug
      when 'motor-performance' then 'engine' when 'suspensao' then 'suspension'
      when 'freios' then 'brakes' when 'rodas-pneus' then 'wheels'
      when 'transmissao' then 'transmission' when 'interior' then 'interior'
      when 'exterior' then 'exterior' when 'iluminacao' then 'lighting'
      when 'eletrica-eletronica' then 'electrical' when 'som' then 'audio' end || '/' || s.slug || '.webp'))
  and m.default_image_path is distinct from s.image;
commit;
`;
await writeFile('supabase/migrations/20261027120000_expand_modification_catalog.sql',sql);
const escape=s=>String(s??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const credits=audit.filter(x=>x.image).map(x=>`<article id="${escape(x.slug)}"><h2>${escape(x.name)}</h2><img src="${escape(x.image)}" alt="" width="128" height="128" loading="lazy"><p><a href="${escape(x.review.source.page)}">${escape(x.review.source.title)}</a> — ${escape(x.review.source.author || 'Autoria não informada na ficha de domínio público')}. ${x.review.source.licenseUrl?`<a href="${escape(x.review.source.licenseUrl)}">${escape(x.review.source.license)}</a>`:escape(x.review.source.license)}.${x.review.source.attribution?' '+escape(x.review.source.attribution):''}${x.review.source.rightsMark?' Marcação na fonte: '+escape(x.review.source.rightsMark)+'.':''}</p><p>Alterações: orientação EXIF, redimensionamento proporcional, margens cinza e conversão WebP. ${x.review.source.technicalChangesOnly?'Reprodução integral com alterações técnicas de dimensão/formato, sem adaptação criativa; a licença NoDerivatives continua aplicável.':'A fotografia adaptada mantém a licença ou condição de domínio público indicada.'} Fonte: ${escape(x.review.source.provider || 'Wikimedia Commons')}. Imagem representativa; não comprova compatibilidade.</p></article>`).join('\n');
// Preserve credits for previous assets that may still exist in historical project data.
const prior=await readFile('public/modifications/photo-credits.html','utf8');
if(!prior.includes('catalogo-v2-credits'))await writeFile('public/modifications/photo-credits-v1.html',prior);
await writeFile('public/modifications/photo-credits.html',`<!doctype html><html lang="pt-BR"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Créditos das fotografias — Projeto Garagem</title><style>body{max-width:900px;margin:32px auto;padding:0 20px;font:16px/1.6 system-ui;background:#fafafa;color:#222}article{padding:24px 0;border-bottom:1px solid #ddd}img{object-fit:contain;background:#f5f5f5}a{color:#934000}h2{font-size:20px}</style><!-- catalogo-v2-credits --><h1>Fotografias do catálogo</h1><p>Fotos reais com fonte e licença identificadas. As imagens representam tipos de peças e não indicam marca ou aplicação recomendada. Itens sem fotografia aprovada aparecem como “Foto em revisão”.</p><p><a href="/modifications/photo-credits-v1.html">Créditos de imagens anteriores</a></p>${credits}</html>\n`);
const approved=audit.filter(x=>x.image),legacyApproved=approved.filter(x=>x.legacy);
const uniquePaths=[...new Set(approved.map(x=>x.image))];
let totalBytes=0;for(const image of uniquePaths)totalBytes+=(await readFile(path.join(root,'public',image))).length;
const kept=legacyApproved.filter(x=>x.review.previousSourceTitle===x.review.source.title).length;
const summary={date:'2026-10-27',mode:'local-only',original:oldItems.size,total:definitions.length,new:definitions.length-oldItems.size,categoriesBefore:categories.length,categoriesAfter:categories.length,selectableWithoutLegacyAliases:definitions.filter(x=>!x.selectionAliasOf).length,approvedPhotos:approved.length,legacyPhotoSourcesPreserved:kept,legacyPhotoSourcesReplaced:legacyApproved.length-kept,legacyImagesWithdrawn:oldItems.size-legacyApproved.length,newItemsWithPhoto:approved.filter(x=>!x.legacy).length,pendingPhotos:audit.filter(x=>!x.image).length,byteIdenticalLegacyFilesPreserved:0,normalizedWebpFiles:uniquePaths.length,totalImageBytes:totalBytes,remoteWrites:0,published:false};
await writeFile('docs/catalogo-2026-10-27/summary.json',JSON.stringify(summary,null,2)+'\n');
const csvCell=value=>'"'+String(value??'').replaceAll('"','""')+'"';
const csvRows=rows=>rows.map(row=>row.map(csvCell).join(',')).join('\n')+'\n';
await writeFile('docs/catalogo-2026-10-27/pending-images.csv',csvRows([['slug','nome','categoria','origem','motivo'],...audit.filter(x=>!x.image).map(x=>[x.slug,x.name,x.category,x.legacy?'existente':'novo',x.review.reason])]));
await writeFile('docs/catalogo-2026-10-27/inventory.csv',csvRows([['slug','nome','categoria','origem','foto','licenca','fonte'],...audit.map(x=>[x.slug,x.name,x.category,x.legacy?'existente':'novo',x.image,x.review.source?.license,x.review.source?.page])]));
